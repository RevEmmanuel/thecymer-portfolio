import type { VideoSource } from '@/lib/video';

export type CategoryId = 'fashion' | 'events' | 'birthdays' | 'content' | 'bts';

export interface Category {
  id: CategoryId;
  /** Label used in filters and metadata. */
  label: string;
}

export interface Credit {
  role: string;
  name: string;
}

export interface Still {
  src: string;
  alt: string;
}

export interface Project {
  /** URL-safe id, used in links like /#work/fashion-shoot-01. Must be unique. */
  slug: string;
  title: string;
  category: CategoryId;
  video: VideoSource;
  /** Optional. Shown in metadata when present. */
  year?: number;
  /** Optional client or brand name. Only add with the client's permission. */
  client?: string;
  /** Optional 1–3 sentence description for the project page. */
  description?: string;
  /** Poster image. Defaults to the frame generated by Drive / YouTube. */
  poster?: string;
  /** Optional short, muted MP4 (3–6s, < 1.5MB) that plays when hovering the frame. */
  preview?: string;
  /** Most of thecymer's work is vertical (9:16). Set 'horizontal' for 16:9 films. */
  orientation?: 'vertical' | 'horizontal';
  /** Featured projects appear in the hero frame sequence and in the reel. */
  featured?: boolean;
  credits?: Credit[];
  /** Extra stills or behind-the-scenes photos for the project page. */
  stills?: Still[];
}

export interface Service {
  id: string;
  title: string;
  /** Italic serif emphasis appended to the title. */
  emphasis?: string;
  description: string;
  tags: string[];
  /** Project category used to pick a preview frame. */
  category: CategoryId;
}

export interface ProcessStep {
  title: string;
  body: string;
}

export interface Testimonial {
  quote: string;
  name: string;
  role?: string;
  /** Slug of the related project, if any. */
  project?: string;
}
